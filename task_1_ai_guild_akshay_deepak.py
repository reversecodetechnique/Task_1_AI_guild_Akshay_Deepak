class Task5ModelTrainer:
    """Handles training and evaluation for Task 5 with fixed hyperparameters"""

    def __init__(self, device='cpu'):
        self.device = device
        self.training_history = {
            'train_losses': [],
            'val_losses': [],
            'val_accuracies': [],
            'val_precisions': [],
            'val_recalls': [],
            'val_f1s': []
        }

    def create_data_loaders(self, X_train, y_train, X_val, y_val, X_test, y_test, batch_size=512):
        """Create PyTorch DataLoaders for training, validation, and test sets"""
        X_train_tensor = torch.FloatTensor(X_train).to(self.device)
        y_train_tensor = torch.FloatTensor(y_train).unsqueeze(1).to(self.device)
        X_val_tensor = torch.FloatTensor(X_val).to(self.device)
        y_val_tensor = torch.FloatTensor(y_val).unsqueeze(1).to(self.device)
        X_test_tensor = torch.FloatTensor(X_test).to(self.device)
        y_test_tensor = torch.FloatTensor(y_test).unsqueeze(1).to(self.device)

        train_dataset = TensorDataset(X_train_tensor, y_train_tensor)
        val_dataset = TensorDataset(X_val_tensor, y_val_tensor)
        test_dataset = TensorDataset(X_test_tensor, y_test_tensor)

        train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
        val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False)
        test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False)

        return train_loader, val_loader, test_loader

    def train_epoch(self, model, train_loader, criterion, optimizer):
        """Train the model for one epoch"""
        model.train()
        total_loss = 0.0
        total_samples = 0

        for batch_X, batch_y in train_loader:
            optimizer.zero_grad()
            outputs = model(batch_X)
            outputs_sigmoid = torch.sigmoid(outputs)
            loss = criterion(outputs_sigmoid, batch_y)
            loss.backward()
            optimizer.step()

            total_loss += loss.item() * batch_X.size(0)
            total_samples += batch_X.size(0)

        return total_loss / total_samples

    def validate_epoch(self, model, val_loader, criterion):
        """Validate the model and return comprehensive metrics"""
        model.eval()
        total_loss = 0.0
        total_samples = 0
        all_predictions = []
        all_targets = []

        with torch.no_grad():
            for batch_X, batch_y in val_loader:
                outputs = model(batch_X)
                outputs_sigmoid = torch.sigmoid(outputs)
                loss = criterion(outputs_sigmoid, batch_y)
                predictions = outputs_sigmoid > 0.5

                total_loss += loss.item() * batch_X.size(0)
                total_samples += batch_X.size(0)

                all_predictions.extend(predictions.cpu().numpy())
                all_targets.extend(batch_y.cpu().numpy())

        avg_loss = total_loss / total_samples
        accuracy = accuracy_score(all_targets, all_predictions)
        precision = precision_score(all_targets, all_predictions, zero_division=0)
        recall = recall_score(all_targets, all_predictions, zero_division=0)
        f1 = f1_score(all_targets, all_predictions, zero_division=0)

        return avg_loss, accuracy, precision, recall, f1

    def train_model(self, model, train_loader, val_loader, epochs=100, learning_rate=0.01, weight_decay=0.001):
        """Complete training loop with fixed hyperparameters"""
        criterion = nn.BCELoss()
        optimizer = optim.RMSprop(model.parameters(), lr=learning_rate, weight_decay=weight_decay)

        print(f"\nTraining Configuration:")
        print(f"  Architecture: 3 layers (256→128→64→1) with ReLU + Dropout(0.2) + BatchNorm")
        print(f"  Loss Function: BCELoss")
        print(f"  Optimizer: RMSprop")
        print(f"  Learning Rate: {learning_rate}")
        print(f"  Weight Decay: {weight_decay}")
        print(f"  Training Epochs: {epochs}")
        print("-" * 60)

        for epoch in range(epochs):
            train_loss = self.train_epoch(model, train_loader, criterion, optimizer)
            val_loss, val_accuracy, val_precision, val_recall, val_f1 = self.validate_epoch(
                model, val_loader, criterion)

            self.training_history['train_losses'].append(train_loss)
            self.training_history['val_losses'].append(val_loss)
            self.training_history['val_accuracies'].append(val_accuracy)
            self.training_history['val_precisions'].append(val_precision)
            self.training_history['val_recalls'].append(val_recall)
            self.training_history['val_f1s'].append(val_f1)

            if (epoch + 1) % 10 == 0:
                print(f"Epoch {epoch+1:3d}/{epochs}: "
                      f"Train Loss: {train_loss:.4f}, Val Loss: {val_loss:.4f}, "
                      f"Val F1: {val_f1:.4f}")

        print("\nTraining completed!")
        print(f"Final Validation Metrics:")
        print(f"  Accuracy:  {val_accuracy:.4f}")
        print(f"  Precision: {val_precision:.4f}")
        print(f"  Recall:    {val_recall:.4f}")
        print(f"  F1 Score:  {val_f1:.4f}")

    def evaluate_on_test(self, model, test_loader):
        """Evaluate the trained model on test set"""
        model.eval()
        all_predictions = []
        all_targets = []

        with torch.no_grad():
            for batch_X, batch_y in test_loader:
                outputs = model(batch_X)
                probabilities = torch.sigmoid(outputs)
                predictions = probabilities > 0.5

                all_predictions.extend(predictions.cpu().numpy())
                all_targets.extend(batch_y.cpu().numpy())

        predictions = np.array(all_predictions).flatten()
        targets = np.array(all_targets).flatten()

        accuracy = accuracy_score(targets, predictions)
        precision = precision_score(targets, predictions, zero_division=0)
        recall = recall_score(targets, predictions, zero_division=0)
        f1 = f1_score(targets, predictions, zero_division=0)

        return {
            'predictions': predictions,
            'targets': targets,
            'accuracy': accuracy,
            'precision': precision,
            'recall': recall,
            'f1': f1
        }

