class ModelTrainer:
    """
    Manages the training, evaluation, and hyperparameter tuning process for the neural network.
    """
    def __init__(self, device='cpu'):
        self.device = device
        self.fixed_weight_decay = 0.001  # Fixed L2 regularization per common practice
        self.fixed_epochs = 50           # Fixed number of epochs for each tuning trial

    def create_loaders(self, data, batch_size):
        """
        Creates PyTorch DataLoaders for the training and validation sets.
        Converts NumPy arrays to PyTorch Tensors and moves them to the specified device.
        """
        # Convert training data to tensors
        train_dataset = TensorDataset(
            torch.FloatTensor(data['X_train']).to(self.device),
            torch.FloatTensor(data['y_train']).unsqueeze(1).to(self.device) # unsqueeze for BCELoss
        )
        # Convert validation data to tensors
        val_dataset = TensorDataset(
            torch.FloatTensor(data['X_val']).to(self.device),
            torch.FloatTensor(data['y_val']).unsqueeze(1).to(self.device) # unsqueeze for BCELoss
        )
        # Create DataLoaders with specified batch size
        return (
            DataLoader(train_dataset, batch_size=batch_size, shuffle=True), # Shuffle training data
            DataLoader(val_dataset, batch_size=batch_size, shuffle=False)   # No shuffle for validation
        )

    def evaluate(self, model, val_loader):
        """
        Evaluates the model on the validation set and returns the F1-score.
        """
        model.eval() # Set model to evaluation mode (disables dropout, uses population stats for BatchNorm)
        all_preds, all_targets = [], []
        with torch.no_grad(): # Disable gradient calculation for evaluation
            for X_val, y_val in val_loader:
                outputs = model(X_val)
                preds = torch.sigmoid(outputs) > 0.5 # Convert probabilities to binary predictions (0 or 1)
                all_preds.extend(preds.cpu().numpy()) # Collect predictions
                all_targets.extend(y_val.cpu().numpy()) # Collect true labels
        # Calculate F1-score, handling cases where precision/recall might be undefined
        return f1_score(all_targets, all_preds, zero_division=0)

    def train_model(self, model, train_loader, val_loader, lr):
        """
        Trains a given model with early stopping based on validation loss.
        Returns the best model state and training statistics.
        """ # <-- Ensure this docstring is indented
        criterion = nn.BCELoss().to(self.device)
        optimizer = optim.RMSprop(
            model.parameters(),
            lr=lr,
            weight_decay=self.fixed_weight_decay
        )

        # Early stopping parameters
        best_val_loss = float('inf')
        best_model_state = None
        patience = 8  # Increased from typical 5 for better stability
        patience_counter = 0
        min_epochs = 10  # Minimum epochs before early stopping can kick in

        # Training statistics tracking
        train_losses = []
        val_losses = []
        val_f1_scores = []

        print(f"    Starting training with early stopping (patience={patience}, min_epochs={min_epochs})")

        for epoch in range(self.fixed_epochs):
            # Training phase
            model.train()
            epoch_train_loss = 0.0
            num_batches = 0

            for X_batch, y_batch in train_loader:
                optimizer.zero_grad()
                outputs = model(X_batch)
                loss = criterion(torch.sigmoid(outputs), y_batch)
                loss.backward()
                optimizer.step()

                epoch_train_loss += loss.item()
                num_batches += 1

            avg_train_loss = epoch_train_loss / num_batches
            train_losses.append(avg_train_loss)

            # Validation phase
            model.eval()
            val_loss = 0.0
            val_batches = 0
            all_preds, all_targets = [], []

            with torch.no_grad():
                for X_val, y_val in val_loader:
                    outputs = model(X_val)
                    loss = criterion(torch.sigmoid(outputs), y_val)
                    val_loss += loss.item()
                    val_batches += 1

                    # Collect predictions for F1 calculation
                    preds = torch.sigmoid(outputs) > 0.5
                    all_preds.extend(preds.cpu().numpy())
                    all_targets.extend(y_val.cpu().numpy())

            avg_val_loss = val_loss / val_batches
            val_losses.append(avg_val_loss)

            # Calculate F1 score
            val_f1 = f1_score(all_targets, all_preds, zero_division=0)
            val_f1_scores.append(val_f1)

            # Print epoch statistics
            print(f"    Epoch {epoch+1:2d}/{self.fixed_epochs}: "
                  f"Train Loss: {avg_train_loss:.4f}, "
                  f"Val Loss: {avg_val_loss:.4f}, "
                  f"Val F1: {val_f1:.4f}")

            # Early stopping logic (based on validation loss for stability)
            if avg_val_loss < best_val_loss:
                best_val_loss = avg_val_loss
                best_model_state = model.state_dict().copy()  # Save best model state
                patience_counter = 0
                print(f"    → New best validation loss: {best_val_loss:.4f}")
            else:
                patience_counter += 1

            # Check early stopping conditions
            if epoch >= min_epochs and patience_counter >= patience:
                print(f"    Early stopping triggered at epoch {epoch+1}")
                print(f"    Best validation loss: {best_val_loss:.4f}")
                break

        # Restore best model state
        if best_model_state is not None:
            model.load_state_dict(best_model_state)
            print(f"    Restored model to best state (val_loss: {best_val_loss:.4f})")

        # Return final validation F1 score using the best model
        final_val_f1 = self.evaluate(model, val_loader)

        # Return training statistics for potential analysis
        training_stats = {
            'final_epoch': epoch + 1,
            'best_val_loss': best_val_loss,
            'final_val_f1': final_val_f1,
            'train_losses': train_losses,
            'val_losses': val_losses,
            'val_f1_scores': val_f1_scores,
            'early_stopped': epoch < self.fixed_epochs - 1
        }

        return final_val_f1, training_stats

    def hyperparameter_tune(self, data, param_grid):
        """
        Enhanced hyperparameter tuning with early stopping statistics tracking.
        """
        results = []
        training_histories = []  # Store training curves for analysis

        total_combos = len(list(product(*param_grid.values())))
        print(f"\nStarting grid search of {total_combos} combinations...")
        print(f"Fixed parameters: weight_decay={self.fixed_weight_decay}, max_epochs={self.fixed_epochs}")
        print(f"Early stopping: patience=8, min_epochs=10")

        total_epochs_saved = 0

        for i, params in enumerate(product(*param_grid.values())):
            config = dict(zip(param_grid.keys(), params))
            print(f"\n--- Tuning Trial {i+1}/{total_combos} ---")
            print(f"Config: {config}")

            # Initialize model
            model = IncomeClassifier(
                input_size=data['num_features'],
                architecture=config['architecture'],
                dropout_rate=config['dropout_rate']
            ).to(self.device)

            # Create data loaders
            train_loader, val_loader = self.create_loaders(data, config['batch_size'])

            # Train model with early stopping
            val_f1, training_stats = self.train_model(model, train_loader, val_loader, config['learning_rate'])

            print(f"Final validation F1: {val_f1:.4f}")
            if training_stats['early_stopped']:
                epochs_saved = self.fixed_epochs - training_stats['final_epoch']
                total_epochs_saved += epochs_saved
                print(f"Saved {epochs_saved} epochs with early stopping")

            # Store results
            result_entry = {
                **config,
                'val_f1': val_f1,
                'layers': model.num_layers,
                'final_epoch': training_stats['final_epoch'],
                'best_val_loss': training_stats['best_val_loss'],
                'early_stopped': training_stats['early_stopped']
            }
            results.append(result_entry)
            training_histories.append(training_stats)

        print(f"\n=== EARLY STOPPING SUMMARY ===")
        early_stopped_count = sum(1 for r in results if r['early_stopped'])
        print(f"Models with early stopping: {early_stopped_count}/{total_combos}")
        print(f"Total epochs saved: {total_epochs_saved}")
        print(f"Average epochs per model: {sum(r['final_epoch'] for r in results) / len(results):.1f}")

        results_df = pd.DataFrame(results)

        # Add training histories for potential plotting
        results_df.training_histories = training_histories

        return results_df

    def generate_report(self, results_df):
        """
        Generates and prints a summary report of the hyperparameter tuning results,
        including a table of top configurations and performance visualizations.
        """
        print("\n" + "="*50)
        print("HYPERPARAMETER TUNING REPORT")
        print("="*50)

        # Sort results by validation F1-score in descending order and print top 5
        print("\nTop 5 Configurations (ranked by Validation F1 Score):")
        print(results_df.sort_values('val_f1', ascending=False).head(5)[[
            'architecture', 'layers', 'batch_size', 'dropout_rate', 'learning_rate', 'val_f1'
        ]].to_markdown(index=False)) # Use to_markdown for easy viewing in various environments

        # Performance Visualization using box plots
        plt.figure(figsize=(18, 6)) # Increased figure size for better readability

        # F1 by Architecture
