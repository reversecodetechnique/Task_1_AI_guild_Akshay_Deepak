class DataPreprocessor:
    """
    Handles data loading, preprocessing, and splitting for UCI Adult Income Dataset
    Uses one-hot encoding for categorical variables and standard scaling for normalization
    per Task 1 requirements
    """
    def __init__(self):
        self.scaler = StandardScaler()
        self.label_encoder = LabelEncoder()
        self.categorical_columns = []
        self.numerical_columns = []
        self.feature_names = []
        self.original_shape = None
        self.processed_shape = None

    def load_data(self):
        """Load the UCI Adult Income Dataset from OpenML"""
        print("Loading UCI Adult Income Dataset...")
        try:
            data = fetch_openml(name='adult', version=2, as_frame=True)
            X, y = data.data, data.target
            print(f"Dataset loaded successfully: {X.shape[0]} samples, {X.shape[1]} features")
            return X, y
        except Exception as e:
            print(f"Error loading dataset: {e}")
            return None, None

    def identify_column_types(self, X):
        """Identify categorical and numerical columns"""
        self.categorical_columns = X.select_dtypes(include=['object', 'category']).columns.tolist()
        self.numerical_columns = X.select_dtypes(include=['int64', 'float64']).columns.tolist()

        print(f"\nColumn Analysis:")
        print(f"Categorical columns ({len(self.categorical_columns)}): {self.categorical_columns}")
        print(f"Numerical columns ({len(self.numerical_columns)}): {self.numerical_columns}")

        return self.categorical_columns, self.numerical_columns

    def handle_missing_values(self, X):
        """Handle missing values in the dataset"""
        print(f"\nHandling missing values...")

        # Replace '?' with NaN for proper handling
        X = X.replace('?', np.nan)

        # Check for missing values
        missing_counts = X.isnull().sum()
        if missing_counts.sum() > 0:
            print(f"Missing values found:")
            for col, count in missing_counts[missing_counts > 0].items():
                print(f"   {col}: {count} missing values")

        # Handle categorical missing values with mode
        for col in self.categorical_columns:
            if X[col].isnull().any():
                mode_val_series = X[col].mode()
                mode_value = mode_val_series.iloc[0] if not mode_val_series.empty else 'Unknown'
                X[col] = X[col].fillna(mode_value)
                print(f"   Filled {col} missing values with mode: '{mode_value}'")

        # Handle numerical missing values with median
        for col in self.numerical_columns:
            if X[col].isnull().any():
                median_value = X[col].median()
                X[col] = X[col].fillna(median_value)
                print(f"   Filled {col} missing values with median: {median_value}")

        print(f"Missing values after handling: {X.isnull().sum().sum()}")
        return X

    def apply_one_hot_encoding(self, X):
        """Apply one-hot encoding to categorical variables (Task 1 requirement)"""
        print(f"\nApplying one-hot encoding as per Task 1 requirements...")

        # Store original shape
        self.original_shape = X.shape

        # Convert categorical columns to 'category' dtype for consistent OHE
        for col in self.categorical_columns:
            if col in X.columns:
                X[col] = X[col].astype('category')

        # One-hot encode categorical variables (drop_first=True to avoid multicollinearity)
        X_encoded = pd.get_dummies(X, columns=self.categorical_columns, drop_first=True)

        # Store processed shape and feature names
        self.processed_shape = X_encoded.shape
        self.feature_names = X_encoded.columns.tolist()

        print(f"Shape before encoding: {self.original_shape}")
        print(f"Shape after encoding: {self.processed_shape}")
        print(f"Features increased by: {self.processed_shape[1] - self.original_shape[1]}")

        # Convert to numpy array with float32 for PyTorch compatibility
        X_array = X_encoded.values.astype(np.float32)

        return X_array

    def encode_target_variable(self, y):
        """Encode target variable (>50K = 1, <=50K = 0)"""
