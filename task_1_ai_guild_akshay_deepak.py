class Task4Trainer:
    """Handles Task 4 ablation study on regularization techniques (dropout and weight decay)"""

    def __init__(self, device='cpu'):
        self.device = device
        self.results = []

    def create_data_loaders(self, X_train, y_train, X_val, y_val, batch_size=512):
        """Create PyTorch DataLoaders for training and validation sets"""

        # Convert to tensors
        X_train_tensor = torch.FloatTensor(X_train).to(self.device)
        y_train_tensor = torch.FloatTensor(y_train).unsqueeze(1).to(self.device)

        X_val_tensor = torch.FloatTensor(X_val).to(self.device)
        y_val_tensor = torch.FloatTensor(y_val).unsqueeze(1).to(self.device)

        # Create datasets
        train_dataset = TensorDataset(X_train_tensor, y_train_tensor)
        val_dataset = TensorDataset(X_val_tensor, y_val_tensor)

        # Create data loaders
        train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
        val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False)

        return train_loader, val_loader

    def train_epoch(self, model, train_loader, criterion, optimizer):
        """Train the model for one epoch"""
        model.train()
        total_loss = 0.0
        total_samples = 0

        for batch_X, batch_y in train_loader:
            optimizer.zero_grad()
            outputs = model(batch_X)
            outputs = torch.sigmoid(outputs)  # BCELoss requires sigmoid
            loss = criterion(outputs, batch_y)
            loss.backward()
            optimizer.step()

            total_loss += loss.item() * batch_X.size(0)
            total_samples += batch_X.size(0)

        return total_loss / total_samples

    def validate_epoch(self, model, val_loader, criterion):
        """Validate the model and return comprehensive metrics"""
        model.eval()
        total_loss = 0.0
        total_samples = 0
        all_predictions = []
        all_targets = []

        with torch.no_grad():
            for batch_X, batch_y in val_loader:
                outputs = model(batch_X)
                outputs = torch.sigmoid(outputs)  # BCELoss requires sigmoid
                loss = criterion(outputs, batch_y)
                predictions = outputs > 0.5

                total_loss += loss.item() * batch_X.size(0)
                total_samples += batch_X.size(0)

                all_predictions.extend(predictions.cpu().numpy())
                all_targets.extend(batch_y.cpu().numpy())

        avg_loss = total_loss / total_samples
        accuracy = accuracy_score(all_targets, all_predictions)
        precision = precision_score(all_targets, all_predictions, zero_division=0)
        recall = recall_score(all_targets, all_predictions, zero_division=0)
        f1 = f1_score(all_targets, all_predictions, zero_division=0)

        return avg_loss, accuracy, precision, recall, f1

    def train_model(self, model, train_loader, val_loader, dropout_rate,
                    weight_decay, use_early_stopping, epochs=100):
        """Complete training loop for a model configuration"""

        # Fixed parameters for Task 4
        loss_type = 'BCELoss'
        optimizer_type = 'RMSprop'
        learning_rate = 0.01

        criterion = nn.BCELoss()
        optimizer = optim.RMSprop(model.parameters(), lr=learning_rate, weight_decay=weight_decay)

        train_losses = []
        val_losses = []
        val_accuracies = []
        val_precisions = []
        val_recalls = []
        val_f1s = []

        config_name = f"Dropout_{dropout_rate}_WD_{weight_decay}_ES_{use_early_stopping}"
        print(f"Training {config_name}...")

        best_val_f1 = 0.0
        best_val_accuracy = 0.0
        best_val_precision = 0.0
        best_val_recall = 0.0
        patience = 15
        patience_counter = 0

        for epoch in range(epochs):
            train_loss = self.train_epoch(model, train_loader, criterion, optimizer)
            val_loss, val_accuracy, val_precision, val_recall, val_f1 = self.validate_epoch(
                model, val_loader, criterion)

            train_losses.append(train_loss)
            val_losses.append(val_loss)
            val_accuracies.append(val_accuracy)
            val_precisions.append(val_precision)
            val_recalls.append(val_recall)
            val_f1s.append(val_f1)

            # Early stopping logic if enabled
            if use_early_stopping:
                if val_f1 > best_val_f1:
                    best_val_f1 = val_f1
                    best_val_accuracy = val_accuracy
                    best_val_precision = val_precision
                    best_val_recall = val_recall
                    patience_counter = 0
                else:
                    patience_counter += 1

                if patience_counter >= patience:
                    print(f"  Early stopping at epoch {epoch+1}")
                    break
            else:
                # Without early stopping, just track best metrics
                if val_f1 > best_val_f1:
                    best_val_f1 = val_f1
                    best_val_accuracy = val_accuracy
                    best_val_precision = val_precision
                    best_val_recall = val_recall

            if (epoch + 1) % 10 == 0:
                print(f"  Epoch {epoch+1:2d}: Train Loss: {train_loss:.4f}, "
                      f"Val Loss: {val_loss:.4f}, Val Acc: {val_accuracy:.4f}, Val F1: {val_f1:.4f}")

        return {
            'config_name': config_name,
            'dropout_rate': dropout_rate,
            'weight_decay': weight_decay,
            'use_early_stopping': use_early_stopping,
            'train_losses': train_losses,
            'val_losses': val_losses,
            'val_accuracies': val_accuracies,
            'val_precisions': val_precisions,
            'val_recalls': val_recalls,
            'val_f1s': val_f1s,
            'best_val_accuracy': best_val_accuracy,
            'best_val_precision': best_val_precision,
            'best_val_recall': best_val_recall,
            'best_val_f1': best_val_f1,
            'final_epoch': len(train_losses)
        }

