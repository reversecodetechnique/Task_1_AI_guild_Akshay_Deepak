class Task3Trainer:
    """Handles Task 3 ablation study on loss functions, optimizers, and learning rates"""

    def __init__(self, device='cpu'):
        self.device = device
        self.results = []

    def create_data_loaders(self, X_train, y_train, X_val, y_val, X_test, y_test, batch_size=512):
        """Create PyTorch DataLoaders for training, validation, and test sets"""

        # Convert to tensors
        X_train_tensor = torch.FloatTensor(X_train).to(self.device)
        y_train_tensor = torch.FloatTensor(y_train).unsqueeze(1).to(self.device)

        X_val_tensor = torch.FloatTensor(X_val).to(self.device)
        y_val_tensor = torch.FloatTensor(y_val).unsqueeze(1).to(self.device)

        X_test_tensor = torch.FloatTensor(X_test).to(self.device)
        y_test_tensor = torch.FloatTensor(y_test).unsqueeze(1).to(self.device)

        # Create datasets
        train_dataset = TensorDataset(X_train_tensor, y_train_tensor)
        val_dataset = TensorDataset(X_val_tensor, y_val_tensor)
        test_dataset = TensorDataset(X_test_tensor, y_test_tensor)

        # Create data loaders
        train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
        val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False)
        test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False)

        return train_loader, val_loader, test_loader

    def get_loss_function(self, loss_type):
        """Get loss function based on type"""
        if loss_type == 'BCEWithLogitsLoss':
            return nn.BCEWithLogitsLoss()
        elif loss_type == 'BCELoss':
            return nn.BCELoss()
        else:
            raise ValueError(f"Unsupported loss function: {loss_type}")

    def get_optimizer(self, model, optimizer_type, learning_rate):
        """Get optimizer based on type and learning rate"""
        if optimizer_type == 'Adam':
            return optim.Adam(model.parameters(), lr=learning_rate, weight_decay=1e-4)
        elif optimizer_type == 'SGD':
            return optim.SGD(model.parameters(), lr=learning_rate, momentum=0.9, weight_decay=1e-4)
        elif optimizer_type == 'RMSprop':
            return optim.RMSprop(model.parameters(), lr=learning_rate, weight_decay=1e-4)
        else:
            raise ValueError(f"Unsupported optimizer: {optimizer_type}")

    def train_epoch(self, model, train_loader, criterion, optimizer, loss_type):
        """Train the model for one epoch"""
        model.train()
        total_loss = 0.0
        total_samples = 0

        for batch_X, batch_y in train_loader:
            optimizer.zero_grad()
            outputs = model(batch_X)

            # Apply sigmoid if using BCELoss (not needed for BCEWithLogitsLoss)
            if loss_type == 'BCELoss':
                outputs = torch.sigmoid(outputs)

            loss = criterion(outputs, batch_y)
            loss.backward()
            optimizer.step()

            total_loss += loss.item() * batch_X.size(0)
            total_samples += batch_X.size(0)

        return total_loss / total_samples

    def validate_epoch(self, model, val_loader, criterion, loss_type):
        """Validate the model and return comprehensive metrics"""
        model.eval()
        total_loss = 0.0
        total_samples = 0
        all_predictions = []
        all_targets = []

        with torch.no_grad():
            for batch_X, batch_y in val_loader:
                outputs = model(batch_X)

                # Apply sigmoid if using BCELoss or for predictions
                if loss_type == 'BCELoss':
                    outputs_for_loss = torch.sigmoid(outputs)
                    loss = criterion(outputs_for_loss, batch_y)
                    predictions = outputs_for_loss > 0.5
                else:  # BCEWithLogitsLoss
                    loss = criterion(outputs, batch_y)
                    predictions = torch.sigmoid(outputs) > 0.5

                total_loss += loss.item() * batch_X.size(0)
                total_samples += batch_X.size(0)

                all_predictions.extend(predictions.cpu().numpy())
                all_targets.extend(batch_y.cpu().numpy())

        avg_loss = total_loss / total_samples
        accuracy = accuracy_score(all_targets, all_predictions)
        precision = precision_score(all_targets, all_predictions, zero_division=0)
        recall = recall_score(all_targets, all_predictions, zero_division=0)
        f1 = f1_score(all_targets, all_predictions, zero_division=0)

        return avg_loss, accuracy, precision, recall, f1

    def train_model(self, model, train_loader, val_loader, loss_type, optimizer_type,
                    learning_rate, epochs=50):
        """Complete training loop for a model configuration"""

        criterion = self.get_loss_function(loss_type)
        optimizer = self.get_optimizer(model, optimizer_type, learning_rate)

        train_losses = []
        val_losses = []
        val_accuracies = []
        val_precisions = []
        val_recalls = []
        val_f1s = []

        config_name = f"{loss_type}_{optimizer_type}_LR{learning_rate}"
        print(f"Training {config_name}...")

        best_val_f1 = 0.0
        best_val_accuracy = 0.0
        best_val_precision = 0.0
        best_val_recall = 0.0
        patience = 15
        patience_counter = 0

        for epoch in range(epochs):
            train_loss = self.train_epoch(model, train_loader, criterion, optimizer, loss_type)
            val_loss, val_accuracy, val_precision, val_recall, val_f1 = self.validate_epoch(
                model, val_loader, criterion, loss_type)

            train_losses.append(train_loss)
            val_losses.append(val_loss)
            val_accuracies.append(val_accuracy)
            val_precisions.append(val_precision)
            val_recalls.append(val_recall)
            val_f1s.append(val_f1)

            # Early stopping based on F1 score
            if val_f1 > best_val_f1:
                best_val_f1 = val_f1
                best_val_accuracy = val_accuracy
                best_val_precision = val_precision
                best_val_recall = val_recall
                patience_counter = 0
            else:
                patience_counter += 1

            if patience_counter >= patience:
                print(f"  Early stopping at epoch {epoch+1}")
                break

            if (epoch + 1) % 10 == 0:
                print(f"  Epoch {epoch+1:2d}: Train Loss: {train_loss:.4f}, "
                      f"Val Loss: {val_loss:.4f}, Val Acc: {val_accuracy:.4f}, Val F1: {val_f1:.4f}")

        return {
            'config_name': config_name,
            'train_losses': train_losses,
            'val_losses': val_losses,
            'val_accuracies': val_accuracies,
            'val_precisions': val_precisions,
            'val_recalls': val_recalls,
            'val_f1s': val_f1s,
            'best_val_accuracy': best_val_accuracy,
            'best_val_precision': best_val_precision,
            'best_val_recall': best_val_recall,
            'best_val_f1': best_val_f1,
            'final_epoch': len(train_losses)
        }

