class BestNeuralNetwork(nn.Module):
    """
    Best model from Task 2: 3L_RELU_DROPOUT+BATCHNORM
    Architecture: 256 → 128 → 64 → 1 (output)
    Activation: ReLU
    Regularization: Dropout + BatchNorm
    """

    def __init__(self, input_size, dropout_rate=0.3):
        super(BestNeuralNetwork, self).__init__()

        # Fixed architecture based on best model from Task 2
        self.layer1 = nn.Linear(input_size, 256)
        self.bn1 = nn.BatchNorm1d(256)
        self.dropout1 = nn.Dropout(dropout_rate)

        self.layer2 = nn.Linear(256, 128)
        self.bn2 = nn.BatchNorm1d(128)
        self.dropout2 = nn.Dropout(dropout_rate)

        self.layer3 = nn.Linear(128, 64)
        self.bn3 = nn.BatchNorm1d(64)
        self.dropout3 = nn.Dropout(dropout_rate)

        self.output_layer = nn.Linear(64, 1)

        # Fixed activation function (ReLU)
        self.activation = nn.ReLU()

        # Initialize weights
        self.dropout_rate = dropout_rate
        self._initialize_weights()

    def _initialize_weights(self):
        """Initialize weights using Xavier/Glorot initialization"""
        for layer in [self.layer1, self.layer2, self.layer3, self.output_layer]:
            nn.init.xavier_uniform_(layer.weight)
            nn.init.constant_(layer.bias, 0)

    def forward(self, x):
        """Forward pass through the network"""
        # Layer 1: 256 neurons
        x = self.layer1(x)
        x = self.bn1(x)
        x = self.activation(x)
        x = self.dropout1(x)

        # Layer 2: 128 neurons
        x = self.layer2(x)
        x = self.bn2(x)
        x = self.activation(x)
        x = self.dropout2(x)

        # Layer 3: 64 neurons
        x = self.layer3(x)
        x = self.bn3(x)
        x = self.activation(x)
        x = self.dropout3(x)

        # Output layer
        x = self.output_layer(x)
        return x

