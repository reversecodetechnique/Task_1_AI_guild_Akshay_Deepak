class IncomeClassifier(nn.Module):
    """
    A customizable Feedforward Neural Network for income classification.
    Supports different architectures (depth and width), includes BatchNorm and Dropout.
    """
    def __init__(self, input_size, architecture, dropout_rate=0.2):
        super().__init__()

        # Define hidden layer configurations based on the specified architecture string
        if architecture == 'small':
            hidden_units = [128, 64]  # 2-layer network
            num_layers = 2
        elif architecture == 'medium':
            hidden_units = [256, 128]  # 2-layer network
            num_layers = 2
        elif architecture == 'large':
            hidden_units = [256, 128, 64]  # 3-layer network
            num_layers = 3
        else:
            raise ValueError("Invalid architecture. Choose 'small', 'medium', or 'large'.")

        # Build the sequential layers of the network
        layers = []
        prev_size = input_size # Starting size is the input feature dimension
        for size in hidden_units:
            layers.extend([
                nn.Linear(prev_size, size), # Linear transformation
                nn.BatchNorm1d(size),      # Batch Normalization
                nn.ReLU(),                 # ReLU activation function
                nn.Dropout(dropout_rate)   # Dropout for regularization
            ])
            prev_size = size # Update prev_size for the next layer

        self.layers = nn.Sequential(*layers) # Group all hidden layers into a sequential module
        self.output = nn.Linear(prev_size, 1) # Output layer (1 neuron for binary classification)

        # Store layer count for reporting
        self.num_layers = num_layers

        # Xavier initialization for weights to improve training stability
        self._initialize_weights()

    def _initialize_weights(self):
        """Applies Xavier uniform initialization to linear layer weights."""
        for layer in self.layers:
            if isinstance(layer, nn.Linear):
                nn.init.xavier_uniform_(layer.weight) # Xavier uniform initialization
                nn.init.constant_(layer.bias, 0)      # Initialize biases to zero
        # Initialize output layer weights as well
        nn.init.xavier_uniform_(self.output.weight)
        nn.init.constant_(self.output.bias, 0)


    def forward(self, x):
        """Defines the forward pass of the network."""
        x = self.layers(x) # Pass input through hidden layers
        return self.output(x) # Pass through output layer (raw logits)

