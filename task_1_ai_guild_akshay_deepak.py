class ModelTrainer:
    """
    Enhanced model trainer with better training loop and evaluation.
    Includes AdamW optimizer, ReduceLROnPlateau scheduler, and gradient clipping.
    """
    def __init__(self, device='cpu'):
        self.device = device
        # history for plotting
        self.history = {
            'train_losses': [],
            'val_losses': [],
            'val_accuracies': [],
            'val_f1s': []
        }

    def create_loaders(self, X_data, y_data, batch_size, shuffle=True):
        """Creates a PyTorch DataLoader for given X and y data."""
        dataset = TensorDataset(
            torch.FloatTensor(X_data).to(self.device),
            torch.FloatTensor(y_data).unsqueeze(1).to(self.device)
        )
        return DataLoader(dataset, batch_size=batch_size, shuffle=shuffle)

    def evaluate(self, model, loader, criterion=None):
        """Enhanced evaluation with probability outputs for metrics like ROC AUC."""
        model.eval() # Set model to evaluation mode
        total_loss = 0.0
        all_preds, all_targets, all_probs = [], [], []

        with torch.no_grad(): # Disable gradient calculation
            for X_batch, y_batch in loader:
                outputs = model(X_batch)
                probabilities = torch.sigmoid(outputs)
                predictions = probabilities > 0.5

                if criterion: # Calculate loss if criterion is provided
                    loss = criterion(probabilities, y_batch)
                    total_loss += loss.item() * X_batch.size(0)

                all_preds.extend(predictions.cpu().numpy())
                all_targets.extend(y_batch.cpu().numpy())
                all_probs.extend(probabilities.cpu().numpy()) # Collect probabilities

        avg_loss = total_loss / len(loader.dataset) if criterion else None
        accuracy = accuracy_score(all_targets, all_preds)
        precision = precision_score(all_targets, all_preds, zero_division=0)
        recall = recall_score(all_targets, all_preds, zero_division=0)
        f1 = f1_score(all_targets, all_preds, zero_division=0)

        return avg_loss, accuracy, precision, recall, f1, \
               np.array(all_preds).flatten(), np.array(all_targets).flatten(), np.array(all_probs).flatten()

    def train_model(self, model, train_loader, val_loader, lr=0.001, epochs=50, patience=8, min_delta=0.0001): # Patience 8, epochs 50
        """
        Enhanced training with AdamW optimizer, learning rate scheduler, and gradient clipping.
        Includes early stopping based on validation F1-score.

        Args:
            model (nn.Module): The neural network model to train.
            train_loader (DataLoader): DataLoader for training data.
            val_loader (DataLoader): DataLoader for validation data.
            lr (float): Initial learning rate for the optimizer.
            epochs (int): Maximum number of training epochs.
            patience (int): Number of epochs to wait for improvement before stopping (for early stopping).
            min_delta (float): Minimum change in validation F1 to qualify as an improvement (for early stopping).
        """
        criterion = nn.BCELoss().to(self.device)
        optimizer = optim.AdamW( # Using AdamW for potentially better regularization and performance
            model.parameters(),
            lr=lr,
            weight_decay=0.01 # L2 regularization/weight decay
        )
        scheduler = optim.lr_scheduler.ReduceLROnPlateau( # Learning rate scheduler
            optimizer, mode='max', factor=0.5, patience=5, verbose=True, min_lr=1e-6
        )

        print(f"\nTraining Enhanced Model")
        print(f"Architecture: 512->256->128->64->1, Dropout: 0.3")
        print(f"Epochs: {epochs}, Learning Rate: {lr}, Weight Decay: 0.01")
        print(f"Optimizer: AdamW, Scheduler: ReduceLROnPlateau (patience=5)")
        print(f"Early Stopping: Patience={patience}, Min Delta={min_delta} (on Val F1)")
        print("-" * 80)

        best_val_f1 = -np.inf # Initialize with negative infinity for F1 score
        epochs_no_improve = 0
        best_model_state = None # To save model state at best epoch for early stopping

        for epoch in range(epochs):
            model.train() # Set model to training mode
            train_loss_epoch = 0.0
            for X_batch, y_batch in train_loader:
                optimizer.zero_grad() # Clear gradients
                outputs = model(X_batch) # Forward pass
                loss = criterion(torch.sigmoid(outputs), y_batch) # Calculate loss
                loss.backward() # Backpropagation
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0) # Gradient clipping
                optimizer.step() # Update weights
                train_loss_epoch += loss.item() * X_batch.size(0) # Accumulate loss

            train_loss_avg = train_loss_epoch / len(train_loader.dataset) # Average training loss

            # Evaluate on validation set
            val_loss, val_acc, _, _, val_f1, _, _, _ = self.evaluate(model, val_loader, criterion)

            # Store history for plotting
            self.history['train_losses'].append(train_loss_avg)
            self.history['val_losses'].append(val_loss)
            self.history['val_accuracies'].append(val_acc)
            self.history['val_f1s'].append(val_f1)

            scheduler.step(val_f1) # Update learning rate based on validation F1

            # Early Stopping Logic: Monitor validation F1-score
            if val_f1 > best_val_f1 + min_delta:
                best_val_f1 = val_f1
                epochs_no_improve = 0
                best_model_state = model.state_dict().copy() # Save the model state dict if performance improves
                print(f"Epoch {epoch+1:3d}/{epochs}: "
                      f"Train Loss: {train_loss_avg:.4f}, Val Loss: {val_loss:.4f}, "
                      f"Val F1: {val_f1:.4f} (BEST), Val Acc: {val_acc:.4f}")
            else:
                epochs_no_improve += 1
                print(f"Epoch {epoch+1:3d}/{epochs}: "
                      f"Train Loss: {train_loss_avg:.4f}, Val Loss: {val_loss:.4f}, "
                      f"Val F1: {val_f1:.4f}, Val Acc: {val_acc:.4f} (No improve: {epochs_no_improve})")

            # Check if early stopping criteria are met
            if epochs_no_improve >= patience:
                print(f"\nEarly stopping triggered after {epoch+1} epochs.")
                break

        # Load the best model state if early stopping occurred or training finished
        if best_model_state is not None:
            model.load_state_dict(best_model_state)
            print("Loaded best model state from epoch with highest validation F1 score.")
        else:
            print("No improvement observed, using final model state (this typically indicates best_model_state was not updated).")

        print("\nTraining Complete.")

